def pinned_code(fdi: str | None, known: dict[str, str] | None = None) -> str | None:
    """The code a framework must keep, or None if it may take a derived code.

    ``known`` is {fdi: code} for frameworks already in the database (read
    from the fdi column), which wins over the static tables.
    """
    if not fdi:
        return None
    seen: set[str] = set()
    current: str | None = fdi
    while current and current not in seen:
        seen.add(current)
        if known and current in known:
            return known[current]
        if current in FRAMEWORK_CODES:
            return FRAMEWORK_CODES[current]
        current = SUCCESSOR_FDI.get(current)
    return None
